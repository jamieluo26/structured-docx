    def reject(self, data, code=None, source=None, **kwargs):
        actual = checked(self.source if source is None else source, self.rendered, data, **kwargs)
        EVENTS.append({"case": self.id(), "actual_sha256": sha(data), "bytes": len(data),
                       "status": actual.status, "code": actual.code,
                       "observed_items": len(actual.observed),
                       "mismatches": actual.mismatches, "unknowns": actual.unknowns})
        self.assertNotEqual(actual.status, "PASS")
        if code:
            self.assertIn(code, [x["code"] for x in actual.mismatches+actual.unknowns])
        return actual

