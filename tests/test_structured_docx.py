def members(data):
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        return {entry.filename: z.read(entry) for entry in z.infolist()}


def xml_bytes(root):
    return ET.tostring(root, encoding="utf-8", xml_declaration=True)


def repack(parts, extra=()):
    target = io.BytesIO()
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", UserWarning)
        with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_STORED) as z:
            for name, data in list(parts.items()) + list(extra):
                z.writestr(name, data)
    return target.getvalue()


def edit_xml(data, part, change):
    parts = members(data)
    root = ET.fromstring(parts[part])
    change(root)
    parts[part] = xml_bytes(root)
    return repack(parts)


def body_of(root):
    return root.find(W + "body")


def texts_of(paragraph):
    # A generic descendant event walk, independent of the tool's run parser.
    values = []
    for e in paragraph.iter():
        if e.tag == W + "t":
            values.append(e.text or "")
        elif e.tag == W + "tab":
            values.append("\t")
        elif e.tag in (W + "br", W + "cr"):
            values.append("\n")
    return "".join(values)


def independent_inventory(data):
    """Resolve actual headings and native numbering; return all ordered items."""
    parts = members(data)
    document = ET.fromstring(parts["word/document.xml"])
    styles = ET.fromstring(parts["word/styles.xml"])
    numbering = ET.fromstring(parts["word/numbering.xml"])
    style_nodes = {e.get(W + "styleId"): e for e in styles.findall(W + "style")}
    nums = {e.get(W + "numId"): e for e in numbering.findall(W + "num")}
    abstracts = {e.get(W + "abstractNumId"): e for e in numbering.findall(W + "abstractNum")}
    aliases, counts, actual = {}, {}, []
    for p in body_of(document):
        if p.tag == W + "sectPr":
            continue
        if p.tag != W + "p":
            raise AssertionError("independent oracle encountered extra body content")
        prop = p.find(W + "pPr")
        sid_node = None if prop is None else prop.find(W + "pStyle")
        sid = "Normal" if sid_node is None else sid_node.get(W + "val")
        np = None if prop is None else prop.find(W + "numPr")
        if np is not None:
            nid = np.find(W + "numId").get(W + "val")
            depth = int(np.find(W + "ilvl").get(W + "val"))
            num = nums[nid]
            aid = num.find(W + "abstractNumId").get(W + "val")
            lev = next(e for e in abstracts[aid].findall(W + "lvl")
                       if int(e.get(W + "ilvl")) == depth)
            fmt = lev.find(W + "numFmt").get(W + "val")
            start = int(lev.find(W + "start").get(W + "val"))
            overrides = [e for e in num.findall(W + "lvlOverride")
                         if int(e.get(W + "ilvl")) == depth]
            if overrides:
                start = int(overrides[0].find(W + "startOverride").get(W + "val"))
            if nid not in aliases:
                aliases[nid] = "L" + str(len(aliases))
            key = (nid, depth)
            counts[key] = counts.get(key, start - 1) + 1
            actual.append(("list", depth + 1, aliases[nid], fmt == "decimal",
                           counts[key], texts_of(p)))
        else:
            outline = style_nodes[sid].find("./" + W + "pPr/" + W + "outlineLvl")
            if outline is not None:
                kind, level = "heading", int(outline.get(W + "val")) + 1
            else:
                kind, level = ("title" if sid == "Title" else "paragraph"), 0
            actual.append((kind, level, None, None, None, texts_of(p)))
    return actual


def checked(source, rendered, data=None, **kwargs):
    selected = rendered.docx_bytes if data is None else data
    return tool.verify_docx(
        source, selected,
        expected_docx_sha256=kwargs.pop("output_sha", sha(selected)),
        expected_render_profile_sha256=kwargs.pop("profile_sha", rendered.render_profile_sha256),
        **kwargs
    )


class AssertionBase(unittest.TestCase):
    def assert_pass(self, source, rendered):
        actual = checked(source, rendered)
        EVENTS.append({"case": self.id(), "status": actual.status, "code": actual.code,
                       "source_sha256": sha(source), "docx_sha256": sha(rendered.docx_bytes),
                       "model_sha256": rendered.model_sha256,
                       "profile_sha256": rendered.render_profile_sha256,
                       "mismatches": actual.mismatches, "unknowns": actual.unknowns})
        self.assertEqual(actual.status, "PASS", (actual.code, actual.unknowns))
        self.assertFalse(actual.mismatches)
        self.assertFalse(actual.unknowns)
        return actual

    def assert_rejected(self, source, code=None, path=None, **kwargs):
        with self.assertRaises(tool.DocumentError) as raised:
            tool.render_docx(source, **kwargs)
        error = raised.exception
        EVENTS.append({"case": self.id(), "code": error.code, "path": error.path,
                       "stage": error.stage, "source_sha256": sha(bytes(source))})
        if code:
            self.assertEqual(error.code, code)
        if path:
            self.assertEqual(error.path, path)
        self.assertNotIn("PRIVATE_SENTINEL", str(error))
        return error


