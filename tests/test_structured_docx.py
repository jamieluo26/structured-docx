class SourceValidationTests(AssertionBase):
    def test_duplicate_root_key(self):
        self.assert_rejected(b'{"version":"structured-docx/v1","title":"","title":"PRIVATE_SENTINEL","blocks":[]}', "DUPLICATE_KEY")

    def test_duplicate_nested_key(self):
        self.assert_rejected(b'{"version":"structured-docx/v1","title":"","blocks":[{"type":"paragraph","text":"a","text":"b"}]}', "DUPLICATE_KEY")

    def test_nonfinite_numbers(self):
        for value in (b"NaN", b"Infinity", b"-Infinity"):
            with self.subTest(value=value):
                self.assert_rejected(b'{"version":"structured-docx/v1","title":' + value + b',"blocks":[]}', "NONFINITE_NUMBER")

    def test_malformed_encoding_or_trailing_data(self):
        for raw in (b"\xff", b"{}", encoded(model()) + b"{}", b'{"title":'):
            with self.subTest(raw_sha=sha(raw)):
                self.assert_rejected(raw)

    def test_exact_heading_integer(self):
        for value in (True, False, 1.0, 0, 4, "1", None):
            with self.subTest(value=value):
                self.assert_rejected(encoded(model(blocks=[{"type": "heading", "level": value, "text": ""}])), "HEADING_LEVEL", "$.blocks[0].level")

    def test_exact_ordered_boolean(self):
        for value in (0, 1, "false", None):
            with self.subTest(value=value):
                self.assert_rejected(encoded(model(blocks=[listing(value, [{"text": ""}])])), "LIST_TYPE")

    def test_text_never_coerced(self):
        for value in (None, True, 42, [], {}):
            with self.subTest(value=value):
                self.assert_rejected(encoded(model(blocks=[para(value)])), "TEXT_REQUIRED", "$.blocks[0].text")

    def test_unknown_fields_and_block_types(self):
        for m in (model(extra="PRIVATE_SENTINEL"), model(blocks=[{"type": "table", "rows": []}]),
                  model(blocks=[{"type": "paragraph", "text": "", "hidden": "PRIVATE_SENTINEL"}]),
                  model(blocks=[listing(True, [{"text": "", "unknown": 1}])])):
            with self.subTest(model_sha=sha(encoded(m))):
                self.assert_rejected(encoded(m))

    def test_required_fields_and_arrays(self):
        for m in ({}, {"version": "structured-docx/v1", "title": ""},
                  model(blocks={}), model(blocks=[{"type": "paragraph"}]),
                  model(blocks=[listing(True, {})]), model(version="other")):
            with self.subTest(model_sha=sha(encoded(m))):
                self.assert_rejected(encoded(m))

    def test_empty_root_or_child_lists(self):
        for block in (listing(False, []), listing(True, [{"text": "", "children": listing(False, [])}])):
            with self.subTest(block=block):
                self.assert_rejected(encoded(model(blocks=[block])), "LIST_EMPTY")

    def test_xml_invalid_characters(self):
        for character in ("\x00", "\x01", "\ufffe", "\uffff", "\ud800"):
            with self.subTest(codepoint=ord(character)):
                raw = json.dumps(model(character), ensure_ascii=True).encode()
                self.assert_rejected(raw, "XML_CHARACTER_INVALID")

    def test_metadata_rejections(self):
        for metadata in ({"author": "a"*256}, {"language": "a"},
                         {"language": "en_US"}, {"language": "en-"+"a"*61},
                         {"createdAt": "2026-02-30T00:00:00Z"},
                         {"createdAt": "2026-01-01T00:00:00+00:00"},
                         {"createdAt": "2026-01-01T00:00:00.0Z"}):
            with self.subTest(metadata=metadata):
                self.assert_rejected(encoded(model(**metadata)))

    def test_source_identity_rejections(self):
        self.assert_rejected(encoded(model("PRIVATE_SENTINEL")), "SOURCE_IDENTITY_MISMATCH",
                             expected_source_sha256="0"*64)
        for value in ("z"*64, "A"*64, 1, b"a"*64):
            with self.subTest(identity_type=type(value).__name__):
                self.assert_rejected(encoded(model()), "IDENTITY_FORMAT", expected_source_sha256=value)

    def test_invalid_limits(self):
        for limits in ([], {"blocks": True}, {"blocks": 0}, {"blocks": -1},
                       {"blocks": 1.0}, {"blocks": 1001}, {"unknown": 1}):
            with self.subTest(limits=limits):
                self.assert_rejected(encoded(model()), limits=limits)

    def test_nonbytes_input(self):
        for value in ("{}", {}, None):
            with self.subTest(value_type=type(value).__name__):
                with self.assertRaises(tool.DocumentError) as error:
                    tool.render_docx(value)
                self.assertEqual(error.exception.code, "BYTES_REQUIRED")


class BoundaryTests(AssertionBase):
    def preserve(self, m, expected_texts, **kwargs):
        source = encoded(m)
        rendered = tool.render_docx(source, **kwargs)
        self.assertEqual([x[-1] for x in independent_inventory(rendered.docx_bytes)], expected_texts)
        self.assert_pass(source, rendered)
        return source, rendered

    def test_string_exact_and_over(self):
        text = "汉😀" * 16384
        self.preserve(model(blocks=[para(text)]), ["", text])
        self.assert_rejected(encoded(model(blocks=[para(text+"x")])), "STRING_LIMIT")

    def test_aggregate_exact_and_over(self):
        texts = [("0123456789abcdef"*2048)]*15 + ["tail" * 2120]
        self.assertEqual(sum(map(len, texts)), 500000)
        self.preserve(model(blocks=[para(t) for t in texts]), [""]+texts)
        texts[-1] += "x"
        self.assert_rejected(encoded(model(blocks=[para(t) for t in texts])), "TEXT_LIMIT")

    def test_blocks_exact_and_over(self):
        texts = ["b"+str(i) for i in range(1000)]
        self.preserve(model(blocks=[para(t) for t in texts]), [""]+texts)
        self.assert_rejected(encoded(model(blocks=[para(t) for t in texts]+[para("over")])), "BLOCK_LIMIT")

    def test_items_exact_and_over(self):
        texts = ["i"+str(i) for i in range(2000)]
        block = listing(True, [{"text": t} for t in texts])
        self.preserve(model(blocks=[block]), [""]+texts)
        block["items"].append({"text": "over"})
        self.assert_rejected(encoded(model(blocks=[block])), "LIST_ITEM_LIMIT")

    def test_list_depth_and_model_depth(self):
        nested = listing(False, [{"text": "d4"}])
        for label in ("d3", "d2", "d1"):
            nested = listing(True, [{"text": label, "children": nested}])
        m = model(blocks=[nested])
        self.preserve(m, ["", "d1", "d2", "d3", "d4"], limits={"model_depth": 14})
        self.assert_rejected(encoded(m), "MODEL_DEPTH_LIMIT", limits={"model_depth": 13})
        nested = listing(True, [{"text": "d0", "children": nested}])
        self.assert_rejected(encoded(model(blocks=[nested])), "MODEL_DEPTH_LIMIT")

    def test_lower_list_depth_three_levels(self):
        nested = listing(False, [{"text": "d3"}])
        nested = listing(True, [{"text": "d2", "children": nested}])
        nested = listing(False, [{"text": "d1", "children": nested}])
        source = encoded(model(blocks=[nested]))
        self.preserve(model(blocks=[nested]), ["", "d1", "d2", "d3"],
                      limits={"list_depth": 3})
        self.assert_rejected(
            source, "LIST_DEPTH_LIMIT",
            "$.blocks[0].items[0].children.items[0].children",
            limits={"list_depth": 2})

    def test_raw_json_bytes_exact_and_over(self):
        base = encoded(model())
        exact = base + b" "*(2097152-len(base))
        rendered = tool.render_docx(exact)
        self.assertEqual(rendered.source_sha256, sha(exact))
        self.assert_pass(exact, rendered)
        self.assert_rejected(exact+b" ", "RESOURCE_LIMIT")

    def test_metadata_exact_boundaries(self):
        language = "en-" + "-".join(["a"*8]*6 + ["b"*6])
        self.assertEqual(len(language), 63)
        source = encoded(model(author="作"*255, language=language, createdAt="2000-02-29T23:59:59Z"))
        self.assert_pass(source, tool.render_docx(source))
        self.assert_rejected(encoded(model(language=language+"c")), "STRING_LIMIT")

    def test_lower_source_text_string_blocks_items_depth_limits(self):
        self.preserve(model("abc"), ["abc"], limits={"string_chars": 3, "text_chars": 3})
        self.assert_rejected(encoded(model("abcd")), limits={"string_chars": 3})
        self.assert_rejected(encoded(model("abc", [para("d")])), "TEXT_LIMIT", limits={"text_chars": 3})
        self.assert_rejected(encoded(model(blocks=[para(""), para("")])), "BLOCK_LIMIT", limits={"blocks": 1})
        self.assert_rejected(encoded(model(blocks=[listing(True, [{"text": ""}, {"text": ""}])])), "LIST_ITEM_LIMIT", limits={"list_items": 1})
        two = listing(False, [{"text": "", "children": listing(True, [{"text": ""}])}])
        self.assert_rejected(encoded(model(blocks=[two])), "LIST_DEPTH_LIMIT", limits={"list_depth": 1})
        raw = encoded(model())
        self.assert_pass(raw, tool.render_docx(raw, limits={"source_bytes": len(raw)}))
        self.assert_rejected(raw, limits={"source_bytes": len(raw)-1})

    def test_package_caps_exact_and_below(self):
        source = encoded(model("caps"))
        rendered = tool.render_docx(source)
        parts = members(rendered.docx_bytes)
        caps = {"archive_bytes": len(rendered.docx_bytes), "zip_members": len(parts),
                "uncompressed_bytes": sum(map(len, parts.values())),
                "xml_bytes": max(len(v) for k, v in parts.items() if k.endswith((".xml", ".rels")))}
        for key, value in caps.items():
            with self.subTest(limit=key):
                self.assertEqual(checked(source, rendered, limits={key: value}).status, "PASS")
                failed = checked(source, rendered, limits={key: value-1})
                EVENTS.append({"case": self.id(), "limit": key, "status": failed.status,
                               "code": failed.code, "unknowns": failed.unknowns})
                self.assertNotEqual(failed.status, "PASS")
        self.assertNotEqual(checked(source, rendered, limits={"compression_ratio": 1}).status, "PASS")


