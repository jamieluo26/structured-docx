"""Synthetic in-memory example; importing it creates no files or documents."""
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from structured_docx import render_docx, verify_docx


DEMO_MODEL = {
    "version": "structured-docx/v1",
    "title": "Editable structured document",
    "author": "",
    "language": "en-US",
    "createdAt": "2000-01-01T00:00:00Z",
    "blocks": [
        {"type": "heading", "level": 1, "text": "Literal content and hierarchy"},
        {"type": "paragraph", "text": "  Leading and trailing spaces remain.  "},
        {"type": "paragraph", "text": "中文与 Unicode 😀 — XML literals: <item> & \"text\"."},
        {"type": "paragraph", "text": "A tab follows:\tsecond column\nA literal new line."},
        {"type": "paragraph", "text": ""},
        {"type": "heading", "level": 2, "text": "Mixed native lists"},
        {"type": "list", "ordered": True, "items": [
            {"text": "First numbered item", "children": {"type": "list", "ordered": False, "items": [
                {"text": "Nested bullet", "children": {"type": "list", "ordered": True, "items": [
                    {"text": "Third-level number", "children": {"type": "list", "ordered": False, "items": [
                        {"text": "Fourth-level bullet"}
                    ]}}
                ]}}
            ]}},
            {"text": "Second numbered item"}
        ]},
        {"type": "heading", "level": 3, "text": "An independent list restarts"},
        {"type": "list", "ordered": True, "items": [
            {"text": "This starts at one"}, {"text": "This follows at two"}
        ]},
        {"type": "paragraph", "text": "End of complete synthetic demo."}
    ]
}


def demo():
    """Return generated bytes and independent verification; the caller owns saving/QA."""
    source = json.dumps(DEMO_MODEL, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    rendered = render_docx(source)
    verified = verify_docx(
        source, rendered.docx_bytes,
        expected_docx_sha256=rendered.docx_sha256,
        expected_render_profile_sha256=rendered.render_profile_sha256,
    )
    return source, rendered, verified
